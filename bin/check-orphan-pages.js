#!/usr/bin/env node

// Warns about docs pages that Docusaurus will build and route, but that no
// sidebar entry links to — a page a reader can only reach by guessing the
// URL. sidebars.js is hand-authored in this repo (no _category_.json
// autogeneration), so a moved or newly added file is never wired into
// navigation automatically; this is the check that notices.
//
// A page is exempt, no baseline entry needed, when:
//   - it's excluded from the docs build entirely (leading-underscore partial,
//     same globs as docusaurus.config.js's docs.exclude)
//   - it's frontmatter `draft: true` (never built in production)
//   - it's frontmatter `unlisted: true` (Docusaurus's own mechanism for a
//     page that renders without appearing in navigation)
//
// Everything else that isn't reachable from sidebars.js is either a real gap
// (add it to sidebars.js) or a deliberate exception recorded with a note in
// bin/orphan-pages-baseline.json.
//
//   node bin/check-orphan-pages.js                    # report
//   node bin/check-orphan-pages.js --json             # machine-readable
//   node bin/check-orphan-pages.js --update-baseline  # accept current gaps
//
// Exit codes: 0 clean, 2 orphans (or stale baseline entries) found.

const fs = require('fs');
const path = require('path');
const matter = require('gray-matter');

const DOCS_DIR = path.join(process.cwd(), 'docs');
const SIDEBARS_FILE = path.join(process.cwd(), 'sidebars.js');
const BASELINE = path.join('bin', 'orphan-pages-baseline.json');

const DEFAULT_COMMENT =
  'Pages that render but are not reachable from any sidebar entry in sidebars.js, and that we have ' +
  'decided to leave that way for now. bin/check-orphan-pages.js reports anything not listed here. An ' +
  'empty note means the entry has not been reviewed yet; either wire the page into sidebars.js, mark it ' +
  '`unlisted: true` if it should stay out of navigation on purpose, or fill in the note explaining why it ' +
  "stays excepted. Regenerate with: node bin/check-orphan-pages.js --update-baseline";

// ---------------------------------------------------------------------------
// Doc discovery
// ---------------------------------------------------------------------------

// Mirrors docs.exclude in docusaurus.config.js: '**/_*.{js,jsx,ts,tsx,md,mdx}',
// '**/_*/**', '**/clusters/**'. (ai-cookbook is a separate docs plugin
// instance rooted outside docs/, so it never appears in this walk.)
function isExcludedDocPath(relativePath) {
  const segments = relativePath.split(path.sep);
  const basename = segments[segments.length - 1];

  if (/^_[^.]/.test(basename) && /\.(mdx?|md)$/.test(basename)) return true;
  if (segments.slice(0, -1).some((segment) => segment.startsWith('_'))) return true;
  if (segments.includes('clusters')) return true;

  return false;
}

function walkDocFiles(dir) {
  const results = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...walkDocFiles(full));
    } else if (/\.(md|mdx)$/.test(entry.name)) {
      results.push(full);
    }
  }
  return results;
}

// The doc id Docusaurus (and therefore sidebars.js) uses to address a file:
// its directory path relative to docs/, joined with a frontmatter `id`
// override or else the filename. Unlike a URL, an index file's id keeps the
// literal "index" segment (sidebars.js references 'cloud/get-started/index',
// not 'cloud/get-started') — this must NOT be confused with slug/URL
// computation, which strips it instead.
function computeDocId(relDirFromDocs, basenameNoExt, frontMatterId) {
  const idPart = frontMatterId || basenameNoExt;
  const dir = relDirFromDocs === '.' ? '' : relDirFromDocs.split(path.sep).filter(Boolean).join('/');
  return dir ? `${dir}/${idPart}` : idPart;
}

function readDoc(filePath) {
  const relPath = path.relative(process.cwd(), filePath);
  const relFromDocs = path.relative(DOCS_DIR, filePath);
  const { data: frontMatter } = matter(fs.readFileSync(filePath, 'utf8'));
  const basenameNoExt = path.basename(filePath).replace(/\.(md|mdx)$/, '');
  const docId = computeDocId(path.dirname(relFromDocs), basenameNoExt, frontMatter.id);

  return { filePath, relPath, docId, frontMatter };
}

// ---------------------------------------------------------------------------
// sidebars.js traversal
// ---------------------------------------------------------------------------

// Recognizes every item shape sidebars.js currently uses (string, {type:
// 'doc'}, {type: 'category', link, items}) plus {type: 'link'|'html'} (no doc
// id, skipped) and {type: 'autogenerated'} (not currently used — it's
// commented out in this repo — but handled so that enabling it later doesn't
// make this check start crying wolf about every file underneath it).
function collectIdsFromItems(items, ids) {
  for (const item of items) {
    if (typeof item === 'string') {
      ids.add(item);
      continue;
    }
    if (!item || typeof item !== 'object') continue;

    if (item.type === 'category') {
      if (item.link && item.link.type === 'doc' && item.link.id) ids.add(item.link.id);
      if (Array.isArray(item.items)) collectIdsFromItems(item.items, ids);
    } else if (item.type === 'doc') {
      if (item.id) ids.add(item.id);
    } else if (item.type === 'autogenerated') {
      const dir = path.join(DOCS_DIR, item.dirName || '.');
      if (fs.existsSync(dir)) {
        for (const file of walkDocFiles(dir)) {
          const rel = path.relative(DOCS_DIR, file);
          if (isExcludedDocPath(rel)) continue;
          ids.add(readDoc(file).docId);
        }
      }
    } else if (Array.isArray(item.items)) {
      // Defensive: an unrecognized item type that still nests items.
      collectIdsFromItems(item.items, ids);
    }
  }
}

function collectSidebarIds(sidebarsConfig) {
  const ids = new Set();
  for (const value of Object.values(sidebarsConfig)) {
    if (Array.isArray(value)) collectIdsFromItems(value, ids);
  }
  return ids;
}

function loadSidebarsConfig() {
  delete require.cache[require.resolve(SIDEBARS_FILE)];
  return require(SIDEBARS_FILE);
}

// ---------------------------------------------------------------------------
// Baseline
// ---------------------------------------------------------------------------

function loadBaseline() {
  if (!fs.existsSync(BASELINE)) return { comment: DEFAULT_COMMENT, exceptions: [] };
  return JSON.parse(fs.readFileSync(BASELINE, 'utf8'));
}

// Baseline entries that no longer describe an orphan (the page was wired
// into sidebars.js, marked unlisted, or deleted) are reported so the
// baseline doesn't quietly accumulate stale exceptions.
function applyBaseline(orphans, baseline) {
  const known = new Map(baseline.exceptions.map((e) => [e.path, e]));
  const remaining = orphans.filter((o) => !known.has(o.path));
  const stale = baseline.exceptions.filter((e) => !orphans.some((o) => o.path === e.path)).map((e) => e.path);
  return { remaining, stale };
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

function findOrphans() {
  const sidebarIds = collectSidebarIds(loadSidebarsConfig());
  const allFiles = walkDocFiles(DOCS_DIR);

  const orphans = [];
  const unlisted = [];
  const draft = [];
  let checked = 0;

  for (const file of allFiles) {
    const relFromDocs = path.relative(DOCS_DIR, file);
    if (isExcludedDocPath(relFromDocs)) continue;
    checked++;

    const doc = readDoc(file);
    if (sidebarIds.has(doc.docId)) continue;

    if (doc.frontMatter.draft === true) {
      draft.push(doc.relPath);
    } else if (doc.frontMatter.unlisted === true) {
      unlisted.push({ path: doc.relPath, docId: doc.docId });
    } else {
      orphans.push({ path: doc.relPath, docId: doc.docId });
    }
  }

  return { orphans, unlisted, draft, checked };
}

function report({ remaining, stale, unlisted, checked }) {
  const lines = [];
  lines.push(`Checked ${checked} doc file(s) against sidebars.js.`);
  lines.push('');

  if (unlisted.length) {
    lines.push(`${unlisted.length} page(s) intentionally unlisted (frontmatter \`unlisted: true\`) — OK:`);
    for (const u of unlisted) lines.push(`  ${u.path}`);
    lines.push('');
  }

  if (remaining.length) {
    lines.push('Pages that will render but are not reachable from any sidebar entry:');
    for (const o of remaining) {
      lines.push(`  ${o.path}`);
      lines.push(`      doc id: ${o.docId}`);
    }
    lines.push('');
    lines.push(
      `Add each one to sidebars.js, mark it \`unlisted: true\` if it should render without navigation, ` +
        `or add it to ${BASELINE} with a note if it's a known, accepted exception.`
    );
    lines.push('');
  }

  if (stale.length) {
    lines.push(`Baseline entries that are no longer orphaned (remove from ${BASELINE}):`);
    for (const p of stale) lines.push(`  ${p}`);
    lines.push('');
  }

  const total = remaining.length + stale.length;
  lines.push(total === 0 ? 'No orphaned pages found.' : `${total} issue(s) found.`);
  return lines.join('\n');
}

function main() {
  const args = process.argv.slice(2);
  const json = args.includes('--json');

  const { orphans, unlisted, draft, checked } = findOrphans();
  const baseline = loadBaseline();
  const { remaining, stale } = applyBaseline(orphans, baseline);

  if (args.includes('--update-baseline')) {
    const notes = new Map(baseline.exceptions.map((e) => [e.path, e.note]));
    const updated = {
      comment: baseline.comment || DEFAULT_COMMENT,
      exceptions: orphans.map((o) => ({ path: o.path, note: notes.get(o.path) ?? '' })),
    };
    fs.writeFileSync(BASELINE, `${JSON.stringify(updated, null, 2)}\n`);
    console.log(`Wrote ${BASELINE} with ${updated.exceptions.length} entries. Add a note for any entry that has none.`);
    return 0;
  }

  if (json) {
    console.log(JSON.stringify({ checked, unlisted, draft, remaining, stale }, null, 2));
  } else {
    console.log(report({ remaining, stale, unlisted, checked }));
  }

  return remaining.length + stale.length;
}

module.exports = {
  isExcludedDocPath,
  walkDocFiles,
  computeDocId,
  readDoc,
  collectIdsFromItems,
  collectSidebarIds,
  applyBaseline,
  findOrphans,
  DOCS_DIR,
  BASELINE,
};

if (require.main === module) {
  try {
    const issues = main();
    if (issues > 0) process.exit(2);
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
